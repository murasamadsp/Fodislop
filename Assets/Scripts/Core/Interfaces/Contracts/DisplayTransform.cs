#nullable enable

namespace Fodinae.Rendering.PostProcessing;

/// <summary>
/// Кривая вывода: чем сцен-референсный кадр приводится к диапазону дисплея.
/// </summary>
/// <remarks>
/// Кривая — отдельный слой, а не встроенное свойство конвейера: сравнение
/// «с кривой и без» на одном кадре — единственный способ увидеть, что именно
/// она делает. Числовые значения совпадают с <c>_DisplayTransform</c> в
/// <c>PostProcess.compute</c>.
/// </remarks>
public enum DisplayTransform
{
    /// <summary>
    /// Без сжатия. Всё ярче белой точки срезается при кодировании в плоское
    /// пятно, поэтому режим существует ради сверки «что именно делает
    /// кривая», а не как рабочий. Творческий грейд остаётся тем же;
    /// отключается только финальное сжатие диапазона.
    /// </summary>
    None = 0,

    /// <summary>
    /// Своя кривая: асимптотическая сигмоида по норме с уходом в белое.
    /// Устройство и обоснование — в
    /// <c>Assets/Resources/Shaders/PostProcessing/ColorGrading.hlsl</c>.
    /// </summary>
    Fodinae = 1,
}
