#nullable enable

using UnityEngine;

namespace Kern.World.Terrain;

/// <summary>
/// Куда окно может переехать прямо сейчас, если запрошенное место ещё не
/// приехало с сервера.
/// </summary>
///
/// ЗАЧЕМ ЭТО ЕСТЬ. Собирать окно по частично приехавшим чанкам нельзя: в кадре
/// это дыры, которые потом молча зарастают. Раньше из этого следовало «ждать
/// целиком»: окно стояло на месте, пока игрок шёл, а когда данные приезжали,
/// догоняло камеру одним прыжком. Прыжок длиной в окно — это уже не сдвиг, а
/// полная пересборка с полной выгрузкой девяти текстур, то есть самый дорогой
/// кадр из возможных, и наступал он ровно после самого долгого ожидания.
///
/// Здесь то же требование выполняется иначе: окно переезжает настолько,
/// насколько данные позволяют, и делает это каждый кадр. Промежуточное
/// положение так же полно, как и запрошенное, — просто ближе к старому. Вместо
/// одного прыжка получается несколько дешёвых шагов, и дыр по-прежнему нет.
public static class TerrainWindowAdvance
{
    /// <summary>
    /// Сколько промежуточных положений пробуется между текущим и запрошенным.
    /// </summary>
    ///
    /// Деление пополам, а не перебор: каждая проба читает все чанки окна, и
    /// платить за неё хочется логарифм, а не длину пути. Пяти делений хватает,
    /// чтобы подойти к границе резидентности ближе чем на 1/32 расстояния.
    private const int Probes = 5;

    /// <summary>
    /// Самое дальнее положение окна по пути к <paramref name="requested"/>,
    /// данные для которого уже в памяти. Возвращает <paramref name="committed"/>,
    /// если не приехало ничего.
    /// </summary>
    ///
    /// Резидентность по пути не обязана быть монотонной, поэтому деление
    /// пополам не обещает САМОГО дальнего резидентного положения — оно обещает
    /// резидентное. Этого достаточно: кадр всё равно движется вперёд, а
    /// следующий продолжит с того места.
    public static Vector2Int Resolve(
        Vector2Int committed,
        Vector2Int requested,
        int width,
        int height,
        System.Func<Vector2Int, bool> isResident)
    {
        if (committed == requested)
        {
            return committed;
        }

        Vector2Int near = committed;
        Vector2Int far = requested;
        for (int probe = 0; probe < Probes; probe++)
        {
            Vector2Int middle = Midpoint(near, far);
            if (middle == near || middle == far)
            {
                break;
            }

            if (isResident(middle))
            {
                near = middle;
            }
            else
            {
                far = middle;
            }
        }

        return near;
    }

    private static Vector2Int Midpoint(Vector2Int a, Vector2Int b) =>
        new(a.x + ((b.x - a.x) / 2), a.y + ((b.y - a.y) / 2));
}
